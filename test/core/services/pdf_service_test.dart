import 'dart:async';

import 'package:exam_guard/core/services/pdf/i_pdf_service.dart';
import 'package:exam_guard/core/services/pdf/pdf_service_impl.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('builds a PDF with Bangla, Arabic and typographic characters', () async {
    var loads = 0;
    final service = PdfServiceImpl(
      loadAsset: (key) {
        loads++;
        return rootBundle.load(key);
      },
    );
    const document = PdfTableDocument(
      brand: 'ExamGuard',
      title: 'Exam Security Session Report',
      headerMeta: [PdfMetaItem('Report ID', 'EG-1')],
      metaRows: [
        PdfMetaItem('Institute', 'ঢাকা কলেজ'),
        PdfMetaItem('Room', '12/B'),
        PdfMetaItem('Inspector', 'محمد أحمد'),
      ],
      summaryItems: [
        PdfSummaryItem(label: 'Total', value: '2'),
        PdfSummaryItem(label: 'Critical', value: '1', color: Color(0xFFB42318)),
      ],
      summaryText: '2 violations recorded — 1 critical',
      tableColumns: [
        PdfTableColumn('Time'),
        PdfTableColumn('Severity'),
        PdfTableColumn('Device'),
        PdfTableColumn('Notes', flex: 2),
      ],
      tableRows: [
        [
          PdfTableCell('10:00'),
          PdfTableCell('CRITICAL', color: Color(0xFFB42318)),
          PdfTableCell('Rahim’s AirPods'),
          PdfTableCell('পরীক্ষার্থীর পকেটে পাওয়া গেছে'),
        ],
        [
          PdfTableCell('10:05'),
          PdfTableCell('LOW', color: Color(0xFF3F6E8C)),
          PdfTableCell('هاتف'),
          PdfTableCell('تحت الطاولة (Desk 4)'),
        ],
      ],
      signatures: [
        PdfSignatureBlock(role: 'Invigilator', name: 'রহিম উদ্দিন'),
        PdfSignatureBlock(role: 'Exam Controller'),
      ],
      footerText: 'Generated by ExamGuard · 2026-10-13',
    );

    final printed = <String>[];
    final bytes = await runZoned(
      () => service.buildTableDocument(document),
      zoneSpecification: ZoneSpecification(
        print: (self, parent, zone, line) => printed.add(line),
      ),
    );
    expect(String.fromCharCodes(bytes.take(5)), '%PDF-');
    expect(
      printed.where((l) => l.contains('Unable to find a font')),
      isEmpty,
      reason: printed.join('\n'),
    );

    // Fonts are loaded once and reused.
    await service.buildTableDocument(document);
    expect(loads, 5);
  });

  test('font loading failure surfaces as PdfGenerationException', () async {
    final service = PdfServiceImpl(
      loadAsset: (key) async => throw StateError('missing $key'),
    );
    await expectLater(
      service.buildTableDocument(const PdfTableDocument(title: 'x')),
      throwsA(isA<PdfGenerationException>()),
    );
  });
}
